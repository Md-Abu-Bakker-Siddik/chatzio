/**
 * Flat map of icon id => svg for frontend tab bar.
 *
 * @return array<string, string>
 */
function chatzio_get_tab_icon_library_flat() {
    $lib   = chatzio_get_tab_icon_library();
    $flat  = [];
    foreach ($lib as $options) {
        foreach ($options as $opt) {
            $flat[ $opt['id'] ] = $opt['svg'];
        }
    }
    return $flat;
}

/**
 * All valid icon IDs (for sanitization).
 *
 * @return array<string>
 */
function chatzio_get_tab_icon_ids() {
    $flat = chatzio_get_tab_icon_library_flat();
    return array_keys( $flat );
}

/**
 * Normalize tab_icons for frontend: only allow known icon IDs; fallback to tab key (default icon).
 *
 * @param array<string, string> $tab_icons Saved tab_icons (may contain legacy emoji).
 * @return array<string, string> Tab key => icon id.
 */
function chatzio_normalize_tab_icons_for_frontend( $tab_icons ) {
    $flat   = chatzio_get_tab_icon_library_flat();
    $keys   = [ 'home', 'chat', 'faq', 'products', 'history', 'news' ];
    $result = [];
    foreach ($keys as $key) {
        $val = isset( $tab_icons[ $key ] ) ? $tab_icons[ $key ] : $key;
        $result[ $key ] = isset( $flat[ $val ] ) ? $val : $key;
    }
    return $result;
}
